def service_more_html(s):
    m = SERVICE_MORE.get(s["slug"])
    if not m: return ""
    out = []
    for key in ("flow", "compare"):
        if key in m:
            t, hd, rows, cap = m[key]
            out.append(f'<section class="sec{" alt" if key == "compare" else ""}"><div class="wrap"><h2>{E(t)}</h2>{table_html(hd, rows, cap)}</div></section>')
    if "check" in m:
        t, items, note = m["check"]
        li = "".join(f"<li>{E(i)}</li>" for i in items)
        out.append(f'<section class="sec"><div class="wrap narrow"><h2>{E(t)}</h2><ul class="dots">{li}</ul><p>{E(note)}</p></div></section>')
    by = {x["slug"]: x for x in POSTS}
    li = []
    for slug, note in m.get("related", []):
        x = by.get(slug)
        if not x: print("서비스 페이지 관련 사례 없음(링크 뺌):", s["slug"], slug); continue
        li.append(f'<li><a href="case-{slug}.html">{E(x["region"])} {E(x["title"])}</a><br><small>{E(note)}</small></li>')
    gd = {g["slug"]: g for g in GUIDES}
    gl = "".join(f'<li><a href="{g}.html">{E(gd[g]["q"])}</a></li>' for g in m.get("guides", []) if g in gd)
    if li or gl:
        out.append(f'<section class="sec alt"><div class="wrap narrow"><h2>{E(s["short"])} 관련 시공사례</h2>'
                   + (f'<ul class="dots">{"".join(li)}</ul>' if li else "")
                   + (f'<h3>함께 보면 좋은 전기 상식</h3><ul class="dots">{gl}</ul>' if gl else "")
                   + '</div></section>')
    return "".join(out)

def service_faq(s):
    return list(s["faq"]) + list(SERVICE_MORE.get(s["slug"], {}).get("faq", []))
